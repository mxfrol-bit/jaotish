_MONTHS_GEN = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля",
               "августа", "сентября", "октября", "ноября", "декабря"]


def date_ru(iso: str) -> str:
    """'2026-09-13' → '13 сентября 2026' (для текстов, которые перечитывают позже)."""
    try:
        y, m, d = (int(x) for x in str(iso)[:10].split("-"))
        return f"{d} {_MONTHS_GEN[m - 1]} {y}"
    except (ValueError, IndexError):
        return str(iso)


def is_female(gender: str) -> bool:
    return (gender or "").strip().lower()[:1] in ("ж", "f", "w")


def _gender_word(gender: str) -> str:
    g = (gender or "").strip().lower()[:1]
    if g in ("ж", "f", "w"):
        return "женский"
    if g in ("м", "m"):
        return "мужской"
    return "не указан"


def _system_prompt(gender: str) -> str:
    if is_female(gender):
        note = ("Ты говоришь с женщиной: все формы рода — женские («ты сама», «готова», "
                "«заметила»). О партнёре — «партнёр», без допущений об ориентации, "
                "если человек не уточнил.")
    elif (gender or "").strip():
        note = ("Ты говоришь с мужчиной: все формы рода — мужские («ты сам», «готов», «заметил»). "
                "О партнёре — «партнёр», без допущений об ориентации, если человек не уточнил.")
    else:
        note = "Пол не указан: избегай форм, требующих рода (перестраивай фразы: «тебе удаётся», «ты можешь»)."
